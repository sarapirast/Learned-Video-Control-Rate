"""Gate test: does each frame's own rate-vs-QP slope vary, and can first-pass statistics predict it? (P2, 2026-11-09)

P2's controller (and its rate model, data/v1/320x180/rd/controller_model.json) uses ONE slope per frame type:
bits_j(q) = c x fp_j x 2^(-(q - 30) / s_type). Texture bits fall steeply with QP; motion-vector, header and skip bits
barely move, so frames with different bit make-up should have different slopes. Uses existing data only:
per-frame constant-QP encodes (rd/rd_frames.parquet, QP 18-50, P1 settings) and the first pass at QP 32
(features/fp_stats.parquet: tex / mv / misc bits, intra / inter / skip blocks; fp at QP 30 from fp_bits.parquet).

Part 1, variation: per frame, the OLS slope of log2(bits) on QP over QP 24-42 (the budget levels' range), reported as
s = QP per halving of bits. Spread per encoder and frame type, and the share of the P-frame variance that is between
GOPs (GOP-mean slope) vs within a GOP.
Part 2, prediction of log2 bits_j(q) at q = 24, 28, 36, 42 from the QP-32 first pass, fitted on TRAIN frames:
  M0 global   log2 b = log2 fp32 + a_type + b_type (q - 32)                               (= the controller's form)
  M1 stats    a and b linear in the first-pass make-up: tex/mv/misc bit fractions, intra/skip block fractions,
              log2 fp32 (one OLS per frame type with x and x (q - 32) columns)
  M1+2pt      M1 + the two-point first-pass slope log2(fp32 / fp30) / 2
  M2 oracle   M0 with each frame's own fitted slope (upper bound on what knowing the slope is worth)
Metrics (val, test): per-frame |error| and the GOP total's |error| (all 30 frames at the same q), as % of bits; and
the GOP total's error after calibrating at QP 32 (error(q) - error(32), i.e. as if the controller's online
calibration had fixed the level and only the slope remains).

  /scratch1/aayushso/envs/ee599/bin/python -I scripts/slope_gate.py
Out: results_v1/gates/slope_gate.md
"""
import os

import numpy as np
import pandas as pd

D = "/scratch1/aayushso/ee599/data/v1/320x180"
OUT = "/scratch1/aayushso/ee599/results_v1/gates"
FIT_Q = np.arange(24, 43)
EVAL_Q = (24, 28, 36, 42)


def pct(x):
    return 100 * (2 ** np.asarray(x) - 1)


def ols(X, y):
    return np.linalg.lstsq(X, y, rcond=None)[0]


def design(x, dq, cols, two_pt):
    base = [np.ones(len(x))] + [x[c].to_numpy() for c in cols + (["fp2pt"] if two_pt else [])]
    return np.column_stack(base + [b * dq for b in base])


def main():
    os.makedirs(OUT, exist_ok=True)
    gops = pd.read_csv(f"{D}/gops.csv")[["clip_id", "gop", "split"]]
    rd = pd.read_parquet(f"{D}/rd/rd_frames.parquet", columns=["encoder", "clip_id", "gop", "kind", "qp", "frame",
                                                               "slice_bits"])
    rd = rd[rd.kind == "cqp"]
    st = pd.read_parquet(f"{D}/features/fp_stats.parquet").query("fp_qp == 32")
    fpb = pd.read_parquet(f"{D}/features/fp_bits.parquet")
    fpb = fpb.pivot_table(index=["encoder", "clip_id", "gop", "frame"], columns="fp_qp", values="fp_slice_bits")
    L = ["# Gate: per-frame rate slope (bits vs QP) and whether first-pass statistics predict it", "",
         "Generated by `scripts/slope_gate.py` (definitions in its docstring). No new encodes. "
         "s = QP per halving of bits (OLS over QP 24-42); the controller uses one s per frame type.", ""]
    part2 = []
    for enc in ("x264", "x265"):
        w = rd[rd.encoder == enc].pivot_table(index=["clip_id", "gop", "frame"], columns="qp", values="slice_bits")
        lb = np.log2(np.maximum(w, 8))
        Y = lb[list(FIT_Q)].to_numpy()
        qc = FIT_Q - FIT_Q.mean()
        slope = (Y - Y.mean(1, keepdims=True)) @ qc / (qc @ qc)          # log2 bits per QP (negative)
        f = pd.DataFrame(index=w.index).reset_index().merge(gops, on=["clip_id", "gop"])
        f["b"] = slope
        f["s"] = -1 / np.minimum(slope, -1e-3)
        f["type"] = np.where(f.frame == 0, "I", "P")
        s2 = st[st.encoder == enc].set_index(["clip_id", "gop", "frame"])
        tot = (s2.tex + s2.mv + s2.misc).clip(lower=1)
        blk = (s2.intra_blocks + s2.inter_blocks + s2.skip_blocks).clip(lower=1)
        x = pd.DataFrame({"tex_f": s2.tex / tot, "mv_f": s2.mv / tot, "intra_f": s2.intra_blocks / blk,
                          "skip_f": s2.skip_blocks / blk})
        fb = fpb.loc[enc]
        x["lfp32"] = np.log2(np.maximum(fb[32], 8)).reindex(x.index)
        x["fp2pt"] = ((np.log2(np.maximum(fb[32], 8)) - np.log2(np.maximum(fb[30], 8))) / 2).reindex(x.index)
        f = f.join(x, on=["clip_id", "gop", "frame"])
        for q in EVAL_Q + (32,):
            f[f"y{q}"] = lb[q].to_numpy()
        assert f[["tex_f", "lfp32", "fp2pt"]].notna().all().all()

        # part 1: variation
        v = f.groupby("type").s.describe(percentiles=[.1, .5, .9])[["count", "10%", "50%", "90%", "mean"]]
        p = f[f.type == "P"]
        gm = p.groupby(["clip_id", "gop"]).s.transform("mean")
        between = gm.var() / p.s.var()
        corr = p[["s", "tex_f", "mv_f", "intra_f", "skip_f", "lfp32", "fp2pt"]].corr(method="spearman").s.drop("s")
        L += [f"## {enc}", "", "**Part 1: slope s (QP per halving of bits) per frame**", "",
              v.round(2).reset_index().to_markdown(index=False), "",
              f"P frames: {100 * between:.0f}% of the variance of s is between GOPs (GOP-mean slope), "
              f"{100 * (1 - between):.0f}% within a GOP. Controller's fitted s: see controller_model.json.", "",
              "Spearman correlation of a P frame's s with first-pass statistics: " +
              ", ".join(f"{k} {c:+.2f}" for k, c in corr.items()), ""]

        # part 2: prediction
        cols = ["tex_f", "mv_f", "intra_f", "skip_f", "lfp32"]
        tr = f.split == "train"
        preds = {}
        for typ in ("I", "P"):
            m = f.type == typ
            ccols = [c for c in cols if not (typ == "I" and c in ("intra_f", "skip_f"))]
            for name in ("M0 global", "M1 stats", "M1+2pt", "M2 oracle"):
                # stack train rows over the fit QPs used for evaluation
                XS, YS = [], []
                for q in EVAL_Q + (32,):
                    dq = np.full(int((m & tr).sum()), q - 32.0)
                    xx = f[m & tr]
                    if name == "M0 global":
                        X = np.column_stack([np.ones(len(xx)), dq])
                    elif name == "M2 oracle":
                        X = np.ones((len(xx), 1))
                    else:
                        X = design(xx, dq, ccols, name == "M1+2pt")
                    yy = xx[f"y{q}"].to_numpy() - xx.lfp32.to_numpy()
                    if name == "M2 oracle":
                        yy = yy - xx.b.to_numpy() * dq
                    XS.append(X)
                    YS.append(yy)
                coef = ols(np.vstack(XS), np.concatenate(YS))
                for q in EVAL_Q + (32,):
                    xx = f[m]
                    dq = np.full(len(xx), q - 32.0)
                    if name == "M0 global":
                        X = np.column_stack([np.ones(len(xx)), dq])
                        pr = X @ coef
                    elif name == "M2 oracle":
                        pr = coef[0] + xx.b.to_numpy() * dq
                    else:
                        pr = design(xx, dq, ccols, name == "M1+2pt") @ coef
                    preds.setdefault((name, q), pd.Series(np.nan, index=f.index))
                    preds[(name, q)].loc[xx.index] = pr + xx.lfp32.to_numpy()
        for split in ("val", "test"):
            ms = f.split == split
            for (name, q), pr in preds.items():
                if q == 32:
                    continue
                e = (pr - f[f"y{q}"])[ms]
                g = f[ms].assign(pb=2 ** pr[ms], tb=2 ** f.loc[ms, f"y{q}"],
                                 pb32=2 ** preds[(name, 32)][ms], tb32=2 ** f.loc[ms, "y32"])
                gs = g.groupby(["clip_id", "gop"])[["pb", "tb", "pb32", "tb32"]].sum()
                ge = np.log2(gs.pb / gs.tb)
                ge32 = np.log2(gs.pb32 / gs.tb32)
                part2.append({"encoder": enc, "split": split, "model": name, "q": q,
                              "frame |err| % (median)": np.median(pct(np.abs(e))),
                              "P frame |err| % (median)": np.median(pct(np.abs(e[f.type[ms] == "P"]))),
                              "GOP |err| % (median)": np.median(pct(np.abs(ge))),
                              "GOP |err| % (p90)": np.percentile(pct(np.abs(ge)), 90),
                              "GOP calibrated@32 |err| % (median)": np.median(pct(np.abs(ge - ge32))),
                              "calibrated p90": np.percentile(pct(np.abs(ge - ge32)), 90)})
    P2 = pd.DataFrame(part2)
    L += ["## Part 2: predicting a frame's bits at QP q from the QP-32 first pass (fitted on train)", "",
          "'calibrated@32' = the GOP total's error at q minus its error at QP 32, i.e. what is left after an online "
          "calibration of the level (the controller does this with c_P); this isolates the slope.", ""]
    for split in ("val", "test"):
        L += [f"### {split}", "", P2[P2.split == split].drop(columns="split").round(1).to_markdown(index=False), ""]
    open(f"{OUT}/slope_gate.md", "w").write("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
