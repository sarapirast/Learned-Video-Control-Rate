"""How far over budget do the learned policies go? (v1 rerun of Pavneet's pipeline; no encodes)

Per episode (one GOP x budget x seed, test split), from the RL eval.pkl files:
  over_pct = 100 * max(0, bits / budget - 1); an episode is "over" if bits > budget (no tolerance).
The score penalises 2 points per 1 % over (rclib/metrics.py), so penalty = 2 * over_pct.

  python scripts/v1_overshoot.py      -> results_v1/v1_overshoot.md and .csv
"""
import os
import sys

import numpy as np
import pandas as pd

sys.path.insert(0, "/scratch1/aayushso/ee599/repo-pavneet")
from experiments import analysis as A  # noqa: E402
from rclib import config as C, runner  # noqa: E402

R = "/scratch1/aayushso/ee599/results_v1"
NAMES = {"bc": "BC", "lagr": "Lagrangian PPO", "cql_ppo": "CQL->PPO"}
frames = []
for codec in ("x264", "x265"):
    for arm in ("orig", "dec"):
        C.WORK = f"/scratch1/aayushso/rcwork_v1/{codec}_{arm}"
        df = A.load_runs(False)
        if not len(df):
            continue
        df = df[(df.split == "test") & (df["mode"] == "fixed") & (df.k == df.train_k) & (df.extra == "")]
        infos = runner.Stages("infos").load("infos")
        df = df.assign(encoder=codec, arm=arm, label=df.gid.map(lambda g: infos[g]["gop"].get("label", "")))
        frames.append(df)
d = pd.concat(frames)
d["method"] = d["method"].map(NAMES).fillna(d["method"])


def agg(g):
    o = g.over_pct.to_numpy()
    ov = o[g.over.to_numpy().astype(bool)]
    return pd.Series({
        "episodes": len(o),
        "% over": 100 * np.mean(g.over),
        "% over >1%": 100 * np.mean(o > 1),
        "% over >5%": 100 * np.mean(o > 5),
        "mean over % | over": ov.mean() if len(ov) else 0.0,
        "median | over": np.median(ov) if len(ov) else 0.0,
        "p90 | over": np.percentile(ov, 90) if len(ov) else 0.0,
        "max over %": o.max(),
        "penalty pts": 2 * o.mean(),
        "saving": g.saving.mean(),
        "score": g.score.mean(),
    })


keys = ["encoder", "arm", "method", "k"]
t = d.groupby(keys).apply(agg).reset_index()
t.to_csv(f"{R}/v1_overshoot.csv", index=False)
lab = d.assign(cls=np.where(d.label.isin(["cut", "gradual"]), "cut/gradual", "stable")) \
       .groupby(["encoder", "arm", "method", "cls"]).apply(agg).reset_index()
worst = d.sort_values("over_pct", ascending=False).head(15)[
    ["encoder", "arm", "method", "k", "seed", "gid", "budget", "label", "over_pct", "saving", "score"]]

L = ["# Overshoot size (v1 rerun, test split, per episode)", "",
     "Generated by `scripts/v1_overshoot.py`. One episode = one GOP x budget x seed. `% over` = share of episodes "
     "with bits > budget; `| over` columns describe only those episodes; `penalty pts` = 2 x mean over % "
     "(what the score loses); `saving` is the score before that penalty.", ""]
for enc in ("x264", "x265"):
    L += [f"## {enc}", "", t[t.encoder == enc].drop(columns="encoder").round(2).to_markdown(index=False), ""]
L += ["## Cut/gradual vs stable GOPs (all k pooled)", "", lab.round(2).to_markdown(index=False), "",
      "## The 15 largest overshoots", "", worst.round(2).to_markdown(index=False), ""]
open(f"{R}/v1_overshoot.md", "w").write("\n".join(L) + "\n")
print("\n".join(L[:4]))
print(t.round(2).to_string(index=False))
