"""W3/W4 on the quality-at-budget metric (tracker items 22 + W3/W4): every method by GOP class and lookahead k.

Inputs (no encodes): results_v1/lfq_compare_<codec>_final4.csv (learners + final4 controller per GOP x budget x k,
from scripts/lfq_compare.py --ctrl-tag final4) and results_v1/lfq_compare_<codec>.csv (same rows with the final3
controller). Score in dB = dPSNR_B - 0.17 per 1% over; seeds are averaged per GOP x budget before any comparison.
Flat GOPs are already excluded by lfq_compare.py. CIs: 95% bootstrap over clips.

  A. score by class x k: final3, final4, the search (ceiling; k-independent) and each learner
  B. split k-curves (W4): value of lookahead = score(k) - score(0) per class, paired on GOP x budget, and
     cut - stable difference of that value (does lookahead help cut GOPs more?)
  C. per class, each method - final4 (paired); the gate question: is any learner better than the controller on
     cut GOPs, where a "fixed rule on stable + learned around cuts" gate would use it?
  D. gate upper bound: per k and class, pick the method with the best VAL mean (final4 or a learner), apply on TEST,
     compare with final4 everywhere. Class is a hindsight label (a real gate only sees a cut when it is in the
     lookahead), so this bounds any class-keyed gate from above.

  python -I scripts/w4_class_kcurves.py <x264|x265>
Out: results_v1/w3/class_kcurves_<codec>.md (+ .csv of the per GOP x budget x k table)
"""
import sys

import numpy as np
import pandas as pd

ROOT = "/scratch1/aayushso/ee599"
OUT = f"{ROOT}/results_v1/w3"
KS = (0, 2, 5, 10, 29)
CLASSES = ("stable", "cut", "gradual")
RNG = np.random.default_rng(0)
NB = 2000


def boot(vals, clips, n=NB):
    vals, clips = np.asarray(vals, float), np.asarray(clips)
    u = np.unique(clips)
    idx = {c: np.flatnonzero(clips == c) for c in u}
    ms = np.empty(n)
    for i in range(n):
        ms[i] = np.concatenate([vals[idx[c]] for c in RNG.choice(u, len(u))]).mean()
    return vals.mean(), np.percentile(ms, 2.5), np.percentile(ms, 97.5)


def boot_diff_classes(vals, clips, cls, a="cut", b="stable", n=NB):
    """mean(vals | cls == a) - mean(vals | cls == b), clips resampled (a clip can hold both classes)."""
    vals, clips, cls = np.asarray(vals, float), np.asarray(clips), np.asarray(cls)
    u = np.unique(clips)
    idx = {c: np.flatnonzero(clips == c) for c in u}
    ms = []
    for _ in range(n):
        j = np.concatenate([idx[c] for c in RNG.choice(u, len(u))])
        va, vb = vals[j][cls[j] == a], vals[j][cls[j] == b]
        if len(va) and len(vb):
            ms.append(va.mean() - vb.mean())
    m = vals[cls == a].mean() - vals[cls == b].mean()
    return m, np.percentile(ms, 2.5), np.percentile(ms, 97.5)


def ci(m, lo, hi):
    return f"{m:+.2f} [{lo:+.2f}, {hi:+.2f}]"


def load(codec):
    key = ["split", "gid", "clip", "cls", "budget", "k"]
    d4 = pd.read_csv(f"{ROOT}/results_v1/lfq_compare_{codec}_final4.csv")
    d3 = pd.read_csv(f"{ROOT}/results_v1/lfq_compare_{codec}.csv", usecols=key + ["method", "ctrl"])
    learn = d4.groupby(["method"] + key, as_index=False).score.mean()          # seeds averaged
    ref = d4.drop_duplicates(key)[key + ["ctrl", "search"]]
    c3 = d3.drop_duplicates(key)[key + ["ctrl"]].rename(columns={"ctrl": "final3"})
    ref = ref.merge(c3, on=key, how="left").rename(columns={"ctrl": "final4"})
    assert ref.final3.notna().all(), "final3 controller missing for some rows"
    rows = [learn]
    for m in ("final4", "final3", "search"):
        rows.append(ref[key].assign(method=m, score=ref[m].to_numpy()))
    df = pd.concat(rows, ignore_index=True)
    w = df.pivot_table(index=key, columns="method", values="score").reset_index()
    return df, w


def order(methods):
    first = ["search", "final4", "final3"]
    return first + sorted(m for m in methods if m not in first)


def main(codec):
    df, w = load(codec)
    meths = order(df.method.unique())
    learners = [m for m in meths if m not in ("search", "final4", "final3")]
    L = [f"# W3/W4: methods by GOP class and lookahead k, quality-at-budget metric ({codec})", "",
         "Generated by `scripts/w4_class_kcurves.py` from results_v1/lfq_compare_" + codec + "_final4.csv and "
         "lfq_compare_" + codec + ".csv. Score in dB (dPSNR_B - 0.17 per 1% over; 0 = constant QP spending exactly "
         "the budget). final3/final4 = causal controller without/with previous-GOP history; search = hindsight "
         "ceiling (same for every k); '@prev' = learner on the previous-GOP base QP; res = residual RL on final3, "
         "res@hist on final4. Seeds averaged per GOP x budget; 4 budget levels pooled; flat GOPs excluded. "
         "CIs: 95% bootstrap over clips.", ""]
    for split in ("test", "val"):
        x = w[w.split == split]
        n = x[x.k == 0].groupby("cls").size()
        L += [f"## {split}", "", "GOP x budget rows per k: " + ", ".join(f"{c} {n.get(c, 0)}" for c in CLASSES), ""]
        # A
        tab = []
        for m in meths:
            for c in CLASSES:
                r = {"method": m, "class": c}
                for k in KS:
                    r[f"k{k}"] = x[(x.k == k) & (x.cls == c)][m].mean()
                tab.append(r)
        L += [f"### A. Mean score by class and k ({split})", "", pd.DataFrame(tab).round(3).to_markdown(index=False), ""]
        # B
        tab = []
        for m in [m for m in meths if m != "search"]:
            p = x.pivot_table(index=["gid", "clip", "cls", "budget"], columns="k", values=m).reset_index()
            for kk in (5, 29):
                v = (p[kk] - p[0]).to_numpy()
                r = {"method": m, "k-gain": f"k{kk} - k0"}
                for c in ("stable", "cut"):
                    s = (p.cls == c).to_numpy()
                    r[c] = ci(*boot(v[s], p["clip"][s]))
                r["cut - stable"] = ci(*boot_diff_classes(v, p["clip"], p.cls))
                tab.append(r)
        L += [f"### B. Value of lookahead by class ({split}): score(k) - score(k0), paired on GOP x budget", "",
              pd.DataFrame(tab).to_markdown(index=False), ""]
        # C
        tab = []
        for m in ["final3"] + learners:
            for c in ("stable", "cut"):
                r = {"method": m, "class": c}
                for k in KS:
                    y = x[(x.k == k) & (x.cls == c)]
                    r[f"k{k}"] = ci(*boot((y[m] - y.final4).to_numpy(), y["clip"]))
                tab.append(r)
        L += [f"### C. Method - final4 by class ({split}), paired", "", pd.DataFrame(tab).to_markdown(index=False), ""]
    # D: choose per class on val, evaluate on test
    v, t = w[w.split == "val"], w[w.split == "test"]
    cands = ["final4"] + learners
    tab = []
    for k in KS:
        pick = {}
        for c in CLASSES:
            mv = v[(v.k == k) & (v.cls == c)][cands].mean()
            pick[c] = mv.idxmax()
        y = t[t.k == k]
        gated = np.array([r[pick[c]] for c, r in zip(y.cls, y[cands].to_dict("records"))])
        r = {"k": k, **{f"pick {c}": pick[c] for c in CLASSES},
             "test gated": gated.mean(), "test final4": y.final4.mean(),
             "gated - final4": ci(*boot(gated - y.final4.to_numpy(), y["clip"]))}
        tab.append(r)
    L += ["## D. Gate upper bound: per class, the method with the best val mean, applied on test", "",
          "Class is known in hindsight here, so this is an upper bound for a gate keyed on GOP class.", "",
          pd.DataFrame(tab).round(3).to_markdown(index=False), ""]
    open(f"{OUT}/class_kcurves_{codec}.md", "w").write("\n".join(L) + "\n")
    w.to_csv(f"{OUT}/class_kcurves_{codec}.csv", index=False)
    print("\n".join(L))


if __name__ == "__main__":
    main(sys.argv[1])
