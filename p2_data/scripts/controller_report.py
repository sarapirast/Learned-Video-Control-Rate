"""Report for the causal online base-QP controller (scripts/controller_real.py, real encodes; no new encodes here).

  python scripts/controller_report.py [tag]   -> results_v1/controller_<tag>.md (+ .csv); tag defaults to "final"
  (final = this morning's controller; final2 = v2 with the I-frame budget cap 0.3)

Reads results_v1/controller_real/final_*.parquet (val-chosen setting, every val/test GOP x 4 levels x k) and
tune2_*.parquet (the val tuning grid). Scores: % bits saved at equal PSNR vs the GOP's own constant-QP curve (linear
extrapolation beyond its ends), minus 2 x % over budget. Reference points from the real constant-QP encodes
(rd_native.parquet), no new encodes:
  best constant QP (hindsight)   the lowest integer QP whose own encode fits the budget: saving 0, never over
  estimate held constant         QP = round(base_qp_est_k) from budgets.csv for the whole GOP, no feedback
"""
import glob
import sys

import numpy as np
import pandas as pd

ROOT = "/scratch1/aayushso/ee599"
D = f"{ROOT}/data/v1/320x180"
R = f"{ROOT}/results_v1"
TAG = sys.argv[1] if len(sys.argv) > 1 else "final"
f = pd.concat([pd.read_parquet(p) for p in glob.glob(f"{R}/controller_real/{TAG}_*.parquet")], ignore_index=True)
gops = pd.read_csv(f"{D}/gops.csv")[["clip_id", "gop", "split", "label"]]
f = f.merge(gops, on=["clip_id", "gop"])
f["cls"] = np.where(f.label.isin(["cut", "gradual"]), "cut/gradual", "stable")


def agg(d):
    return pd.Series({"episodes": len(d), "score": d.score.mean(), "saving": d.saving.mean(),
                      "% over": 100 * d.over.mean(), "mean over %": d.over_pct.mean()})


main = f.groupby(["encoder", "split", "k"]).apply(agg).reset_index()
by_lvl = f[f.split == "test"].groupby(["encoder", "level_q0", "k"]).score.mean().unstack("k").round(2)
by_cls = f[f.split == "test"].groupby(["encoder", "cls", "k"]).score.mean().unstack("k").round(2)

# paired k differences on test (same GOP x level), 95% normal CI
pk = []
for enc, d in f[f.split == "test"].groupby("encoder"):
    w = d.pivot_table(index=["clip_id", "gop", "level_q0"], columns="k", values="score")
    for k in [c for c in w.columns if c != 0]:
        x = (w[k] - w[0]).dropna()
        pk.append({"encoder": enc, "k vs 0": k, "mean diff": x.mean(), "95% CI": 1.96 * x.std(ddof=1) / np.sqrt(len(x)),
                   "pairs": len(x)})
pk = pd.DataFrame(pk)

# reference: GOP-start estimate held constant (real CQP encodes), per k
rd = pd.read_parquet(f"{D}/rd/rd_native.parquet")
bud = pd.read_csv(f"{D}/budgets.csv")
rdi = rd.set_index(["encoder", "clip_id", "gop", "qp"]).slice_bits
ref = []
for r in bud[bud.split.isin(["val", "test"])].itertuples():
    for k in (0, 2, 5, 10, 29):
        q = int(np.clip(round(getattr(r, f"base_qp_est_k{k}")), 18, 50))
        bits = rdi[(r.encoder, r.clip_id, r.gop, q)]
        over = 100 * max(0.0, bits / r.budget_bits - 1)
        ref.append({"encoder": r.encoder, "split": r.split, "k": k, "score": -2 * over, "over": bits > r.budget_bits,
                    "over_pct": over})
ref = pd.DataFrame(ref).groupby(["encoder", "split", "k"]).agg(score=("score", "mean"), pct_over=("over", lambda s: 100 * s.mean()),
                                                              mean_over=("over_pct", "mean")).reset_index()
t2 = glob.glob(f"{R}/controller_real/tune2_*.parquet")
tune = (pd.concat([pd.read_parquet(p) for p in t2]).groupby(["encoder", "setting"]).score.mean().unstack(0).round(2)
        if t2 else pd.DataFrame())
main.to_csv(f"{R}/controller_{TAG}.csv", index=False)
setting = f.setting.iloc[0]
L = ["# Causal online base-QP controller: results (real encodes)", "",
     f"Generated by `scripts/controller_report.py {TAG}` from `results_v1/controller_real/{TAG}_*.parquet` "
     "(`scripts/controller_real.py`). Budgets: clip-level, 4 levels (`budgets.csv`). Encoders on P1's frozen "
     f"settings. Setting (chosen on val, tag tune2): `{setting}` (margin:dI:i_cap:w0:dmax:fcap:init:pmin). "
     "Score = % bits saved at equal PSNR vs the GOP's own constant-QP curve, minus 2 x % over budget; 0 = as "
     "efficient as the best constant QP in hindsight.", "",
     "## Controller by lookahead k", "", main.round(2).to_markdown(index=False), "",
     "## Reference: GOP-start estimate held constant (no feedback; real constant-QP encodes)", "",
     "Its saving is 0 by construction (it is a point on the GOP's own curve), so its score is only the budget "
     "penalty.", "", ref.round(2).to_markdown(index=False), "",
     "## Test: does lookahead help? (paired difference to k = 0, same GOP and level)", "", pk.round(2).to_markdown(index=False), "",
     "## Test score by budget level", "", by_lvl.to_markdown(), "",
     "## Test score, stable vs cut/gradual GOPs", "", by_cls.to_markdown(), ""]
if len(tune):
    L += ["## Tuning grid (val, every 2nd GOP, k = 0 and 5 pooled; clamped scoring, used only for ranking)", "",
          tune.to_markdown(), ""]
open(f"{R}/controller_{TAG}.md", "w").write("\n".join(L) + "\n")
print("\n".join(L[:30]))
