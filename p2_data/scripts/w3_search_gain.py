"""Week 3: where does the hindsight search's gain come from? (P2, docs/p2-plan.md "Week 3"; tracker item 22)

Reads one encoder x budget arm of the search (Pavneet's hill-climb; repo-pavneet rclib/search.py) and writes:
  1. gain by GOP class (stable / cut / gradual) per split and budget: start score, best score, gain = best - start
  2. the search's QP changes around cuts: offsets of the best plan relative to its start plan, minus the mean offset of
     stable GOPs at the same frame position and budget (removes the search's general position effect), aligned on
     the cut frame c (single-cut GOPs, val + test pooled; train added separately because it has the spliced clips)
  3. the key measurement: per cut GOP, the change BEFORE the cut (frames c-3..c-1; needs lookahead) vs AT/AFTER it
     (frames c..c+2; reachable at k=0 because the current frame's cut flag is visible)
CIs: 95% bootstrap over clips (GOPs of one clip are not independent).
Flat (grayscale) GOPs in data/v1/320x180/rd/flat_gops.csv are excluded (scripts/flat_gops_v1.py; their score is not
meaningful under the mean-of-frames YUV PSNR); RC_KEEP_FLAT=1 keeps them.

  python -I scripts/w3_search_gain.py <x264|x265> <orig|dec|lf|lfq>   (lfq = the quality-at-budget search, dB)
Out: results_v1/w3/search_gain_<codec>_<arm>.md and .csv (per GOP x budget rows)
"""
import os
import pickle
import sys

import numpy as np
import pandas as pd

ROOT = "/scratch1/aayushso/ee599"
OUT = f"{ROOT}/results_v1/w3"
ACTIONS = {"orig": tuple(range(-3, 4)), "dec": tuple(range(-3, 4)), "lf": tuple(range(-5, 6)), "lfq": tuple(range(-5, 6))}
WIN = 6             # aligned window: c-WIN .. c+WIN
PRE, POST = (-3, -1), (0, 2)
RNG = np.random.default_rng(0)
FLAT_CSV = f"{ROOT}/data/v1/320x180/rd/flat_gops.csv"


def flat_gids():
    if os.environ.get("RC_KEEP_FLAT") == "1":
        return set()
    f = pd.read_csv(FLAT_CSV)
    return set(f.gid[f.flat])


def load(codec, arm):
    work = f"/scratch1/aayushso/rcwork_v1/{codec}_{arm}"
    infos = pickle.load(open(f"{work}/results_infos/infos.pkl", "rb"))
    rows, flat, n_flat = [], flat_gids(), {}
    for split in ("train", "val", "test"):
        p = f"{work}/results_search/search_{split}.pkl"
        if not os.path.exists(p):
            continue
        res = pickle.load(open(p, "rb"))
        n_flat[split] = sum(g in flat for g in res)
        for gid, r in res.items():
            if gid in flat:
                continue
            g = infos[gid]["gop"]
            for b, x in r.items():
                acts = np.asarray(ACTIONS[arm])[np.asarray(x["best_acts"], int)]
                rows.append({"gop": gid, "clip": g["clip"], "family": g["family"], "split": split, "budget": b,
                             "cls": g["label"], "cuts": tuple(g["cuts"]), "start": float(x["static_score"]),
                             "best": float(x["best_score"]), "saving": float(x["saving"]), "over": bool(x["over"]),
                             "base_q": x.get("base_q", b), "offs": acts})
    df = pd.DataFrame(rows)
    df["gain"] = df.best - df.start
    df.attrs["n_flat"] = n_flat
    return df


def boot_ci(vals, clips, n=2000):
    """Mean and 95% bootstrap CI, resampling clips."""
    vals, clips = np.asarray(vals, float), np.asarray(clips)
    u = np.unique(clips)
    if len(u) < 2:
        return float(vals.mean()) if len(vals) else np.nan, np.nan, np.nan
    idx = {c: np.flatnonzero(clips == c) for c in u}
    ms = []
    for _ in range(n):
        pick = RNG.choice(u, len(u))
        v = np.concatenate([vals[idx[c]] for c in pick])
        ms.append(v.mean())
    return float(vals.mean()), float(np.percentile(ms, 2.5)), float(np.percentile(ms, 97.5))


def md(df, floatfmt=2):
    cols = [str(c) for c in df.columns]
    lines = ["| " + " | ".join(cols) + " |", "|" + "|".join("---" for _ in cols) + "|"]
    for r in df.itertuples(index=False):
        lines.append("| " + " | ".join(f"{v:.{floatfmt}f}" if isinstance(v, float) else str(v) for v in r) + " |")
    return "\n".join(lines)


def ci_str(m, lo, hi):
    return f"{m:+.2f} [{lo:+.2f}, {hi:+.2f}]" if np.isfinite(lo) else f"{m:+.2f}"


def main(codec, arm):
    df = load(codec, arm)
    os.makedirs(OUT, exist_ok=True)
    L = [f"# Week 3: where the search's gain comes from ({codec}, arm {arm})", "",
         "Generated by `scripts/w3_search_gain.py`. " + (
             "Score (dB): dPSNR_B = PSNR - constant-QP PSNR at exactly the budget, minus 0.17 dB per 1% over."
             if arm == "lfq" else
             "Score: % bits saved at equal PSNR vs the GOP's own constant-QP curve, minus 2 per 1% over budget."),
         "'start' = the search's start plan (orig/dec: STATIC at the budget QP;",
         "lf/lfq: the ramp at the hindsight base q); gain = best - start. CIs are 95% bootstraps over clips.",
         "Excluded flat (grayscale) GOPs per split (data/v1/320x180/rd/flat_gops.csv): "
         + ", ".join(f"{k} {v}" for k, v in df.attrs["n_flat"].items()) + ".", ""]

    # 1. gain by class
    L += ["## 1. Gain by GOP class", ""]
    for split in ("test", "val", "train"):
        d = df[df.split == split]
        if d.empty:
            continue
        t = d.groupby(["budget", "cls"]).agg(n=("gain", "size"), start=("start", "mean"), best=("best", "mean"),
                                             gain=("gain", "mean"), best_median=("best", "median"),
                                             gain_median=("gain", "median"), pct_over=("over", "mean")).reset_index()
        t["pct_over"] *= 100
        L += [f"**{split}** (by budget and class)", "", md(t), ""]
        cis = []
        for cls in ("stable", "cut", "gradual"):
            x = d[d.cls == cls]
            if len(x):
                cis.append({"class": cls, "n": len(x), "gain (all budgets)": ci_str(*boot_ci(x.gain, x["clip"])),
                            "best (all budgets)": ci_str(*boot_ci(x.best, x["clip"]))})
        L += [md(pd.DataFrame(cis)), ""]

    # 2./3. offsets around cuts
    def resid_table(d_all):
        st = d_all[d_all.cls == "stable"]
        ctrl = {b: np.mean(np.stack(x.offs.to_list()), 0) for b, x in st.groupby("budget")}
        cut = d_all[(d_all.cls == "cut") & (d_all.cuts.map(len) == 1)].copy()
        cut["c"] = cut.cuts.map(lambda c: c[0])
        cut["res"] = [o - ctrl[b] for o, b in zip(cut.offs, cut.budget)]
        return cut, ctrl

    for label, sel in (("val + test (natural cuts)", ["val", "test"]), ("train (incl. spliced clips)", ["train"])):
        d = df[df.split.isin(sel)]
        if d.empty or not (d.cls == "cut").any():
            continue
        cut, ctrl = resid_table(d)
        L += [f"## 2. Search offsets around cuts: {label}", "",
              f"{cut.gop.nunique()} single-cut GOPs x {cut.budget.nunique()} budgets = {len(cut)} rows. Residual = best-plan",
              "offset minus the stable-GOP mean offset at the same frame and budget (QP units; negative = more bits).", ""]
        rel = []
        for k in range(-WIN, WIN + 1):
            v, cl = [], []
            for r in cut.itertuples():
                t = r.c + k
                if 1 <= t <= 29:          # P frames only (frame 0 is the I frame)
                    v.append(r.res[t])
                    cl.append(r.clip)
            if v:
                m, lo, hi = boot_ci(v, cl)
                rel.append({"frame rel. to cut": f"{k:+d}" if k else "0 (cut)", "n": len(v), "mean residual QP": m,
                            "ci_lo": lo, "ci_hi": hi})
        L += [md(pd.DataFrame(rel)), ""]

        # 3. before vs at/after
        rows = []
        for r in cut.itertuples():
            pre = [r.res[t] for t in range(r.c + PRE[0], r.c + PRE[1] + 1) if 1 <= t <= 29]
            post = [r.res[t] for t in range(r.c + POST[0], r.c + POST[1] + 1) if 1 <= t <= 29]
            if pre and post:
                rows.append({"clip": r.clip, "budget": r.budget, "c": r.c, "pre": np.mean(pre), "post": np.mean(post),
                             "pre_abs": np.mean(np.abs(pre)), "post_abs": np.mean(np.abs(post))})
        b = pd.DataFrame(rows)
        if len(b):
            share = b.pre_abs.sum() / (b.pre_abs.sum() + b.post_abs.sum())
            L += [f"## 3. Before vs at/after the cut: {label}", "",
                  f"Frames c{PRE[0]}..c{PRE[1]} (before; needs lookahead) vs c+{POST[0]}..c+{POST[1]} (at/after; reachable"
                  " at k=0). GOPs where both windows exist: " + str(len(b)) + " rows.", "",
                  f"- mean residual BEFORE: {ci_str(*boot_ci(b.pre, b['clip']))} QP",
                  f"- mean residual AT/AFTER: {ci_str(*boot_ci(b.post, b['clip']))} QP",
                  f"- mean |residual| before: {b.pre_abs.mean():.2f}, at/after: {b.post_abs.mean():.2f} QP",
                  f"- share of the QP-change magnitude that is BEFORE the cut: {100 * share:.0f}%",
                  "- the same by cut position (early c <= 10, mid 11-20, late > 20):", ""]
            b["pos"] = pd.cut(b.c, [0, 10, 20, 30], labels=["early", "mid", "late"])
            t = b.groupby("pos", observed=True).agg(n=("pre", "size"), before=("pre", "mean"), after=("post", "mean"),
                                                    abs_before=("pre_abs", "mean"),
                                                    abs_after=("post_abs", "mean")).reset_index()
            t["pos"] = t["pos"].astype(str)
            L += [md(t), ""]
        cut.drop(columns=["offs", "res"]).assign(split_set=label).to_csv(
            f"{OUT}/search_cuts_{codec}_{arm}_{sel[0]}.csv", index=False)

    df.drop(columns=["offs"]).to_csv(f"{OUT}/search_gain_{codec}_{arm}.csv", index=False)
    out = f"{OUT}/search_gain_{codec}_{arm}.md"
    open(out, "w").write("\n".join(L) + "\n")
    print("\n".join(L))
    print(f"-> {out}")


if __name__ == "__main__":
    main(*sys.argv[1:3])
