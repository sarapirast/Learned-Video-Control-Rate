"""Budget shield vs no shield, per model (v1 rerun; reads eval.pkl and shield_<split>.pkl; no encodes).

  python scripts/v1_shield_compare.py x264 orig val      -> results_v1/<codec>_<arm>_shield_<split>.md and .csv

Per model and setting: score, saving, % of episodes over budget, mean over %, shield fires per GOP. 'none' is the
unshielded result from eval.pkl on the same split. The tolerance chosen per method is the one with the best mean
score over all k on this split (only meaningful when the split is val).
"""
import glob
import os
import pickle
import sys

import numpy as np
import pandas as pd

codec, arm, split = (sys.argv[1:4] + ["x264", "orig", "val"][len(sys.argv[1:4]):])[:3]
W = f"/scratch1/aayushso/rcwork_v1/{codec}_{arm}/results_rl"
NAMES = {"bc": "BC", "cql_ppo": "CQL->PPO", "lagr": "Lagrangian PPO"}


def summ(rows):
    return {"episodes": len(rows), "score": np.mean([r["score"] for r in rows]),
            "saving": np.mean([r["saving"] for r in rows]), "% over": 100 * np.mean([r["over"] for r in rows]),
            "mean over %": np.mean([r["over_pct"] for r in rows]),
            "fires/GOP": np.mean([r.get("shield_fires", 0) for r in rows])}


out = []
for p in sorted(glob.glob(f"{W}/*/shield_{split}.pkl")):
    run = os.path.basename(os.path.dirname(p))
    ev = pickle.load(open(os.path.join(os.path.dirname(p), "eval.pkl"), "rb"))
    a = ev["args"]
    base = ev["res"][(a["mode"], a["k"], split)]
    sh = pickle.load(open(p, "rb"))
    meta = {"method": NAMES.get(a["method"], a["method"]), "k": a["k"], "seed": a["seed"]}
    out.append({**meta, "setting": "none", **summ(base)})
    for key, rows in sorted(sh.items()):
        out.append({**meta, "setting": f"tol {key[2]:g}", **summ(rows)})
t = pd.DataFrame(out)
if not len(t):
    sys.exit(f"no shield_{split}.pkl files under {W}")
R = "/scratch1/aayushso/ee599/results_v1"
t.to_csv(f"{R}/{codec}_{arm}_shield_{split}.csv", index=False)
pooled = t.groupby(["method", "setting"])[["score", "saving", "% over", "mean over %", "fires/GOP"]].mean().reset_index()
best = pooled[pooled.setting != "none"].sort_values("score").groupby("method").tail(1)
L = [f"# Budget shield vs none ({codec}, {arm} budget, {split})", "",
     "Generated by `scripts/v1_shield_compare.py`. Shield = `rclib/policies.Shield` (repo-pavneet, v1-data); "
     "tol = extra tolerance at frame 0, shrinking linearly to 0 at the last frame; future frames assumed at +3; "
     "bit model fitted on train only. 'none' = the same model without the shield.", "",
     "## Pooled over k (mean of the per-model numbers)", "", pooled.round(2).to_markdown(index=False), "",
     f"## Tolerance chosen per method on {split}", "", best.round(2).to_markdown(index=False), "",
     "## Per model", "", t.round(2).to_markdown(index=False), ""]
open(f"{R}/{codec}_{arm}_shield_{split}.md", "w").write("\n".join(L) + "\n")
print("\n".join(L[:12]))
