"""What does the residual RL learn on top of P2's controller? (tracker item 27d diagnosis, P2 2026-11-09)

Reads rcwork_v1/<codec>_res/results_rl/res_k*_fixed_s*/eval.pkl (per episode: qps = QPs actually used, ctrl_qps =
what the controller proposed at each frame given the history so far, i.e. offset = qps - ctrl_qps) and the
controller's own standalone run on the same GOP x level x k (infos ctrl qps).
Reports, per k (test, seeds pooled):
  1. offset distribution (-3..+3), share at the limits
  2. mean signed offset by frame position band, overall and by budget level and by GOP class
  3. net QP change vs the controller's standalone run, by position band (the controller reacts to the offsets with
     its feedback, so the net change can differ from the offsets)
  4. how much of the offset variance a fixed pattern explains: R^2 of the per-(position, level) mean offset, and of
     the per-(position, level, clip) mean (a pattern that also knows the clip)
If (4) is high, the residual is mostly a fixed QP pattern on top of the controller, which a retuned non-learned
controller could reproduce; if low, it reacts to the state.

  /scratch1/aayushso/envs/ee599/bin/python -I scripts/res_offsets.py [x264] [split]
Out: results_v1/res_offsets_<codec>.md
"""
import glob
import os
import pickle
import re
import sys

import numpy as np
import pandas as pd

RC = "/scratch1/aayushso/rcwork_v1"
OUT = "/scratch1/aayushso/ee599/results_v1"
BANDS = [(0, 0, "I (0)"), (1, 1, "P1"), (2, 4, "P2-4"), (5, 14, "P5-14"), (15, 24, "P15-24"), (25, 29, "P25-29")]


def band(t):
    for a, b, n in BANDS:
        if a <= t <= b:
            return n


def md(df):
    cols = list(df.columns)
    L = ["| " + " | ".join(map(str, cols)) + " |", "|" + "|".join("---" for _ in cols) + "|"]
    for r in df.itertuples(index=False):
        L.append("| " + " | ".join(f"{v:.2f}" if isinstance(v, float) else str(v) for v in r) + " |")
    return "\n".join(L)


def r2(y, groups):
    m = y.groupby(groups).transform("mean")
    return 1 - ((y - m) ** 2).sum() / ((y - y.mean()) ** 2).sum()


def main(codec="x264", split="test"):
    work = f"{RC}/{codec}_res"
    infos = pickle.load(open(f"{work}/results_infos/infos.pkl", "rb"))
    rows = []
    for p in sorted(glob.glob(f"{work}/results_rl/res_k*_fixed_s*/eval.pkl")):
        m = re.match(r"res_k(\d+)_fixed_s(\d+)$", os.path.basename(os.path.dirname(p)))
        seed = int(m.group(2))
        for (_, k, sp), eps in pickle.load(open(p, "rb"))["res"].items():
            if sp != split:
                continue
            for e in eps:
                g = infos[e["gid"]]
                alone = g["ctrl"][(e["budget"], k)]["qps"]
                for t in range(30):
                    rows.append((k, seed, e["gid"], g["gop"]["clip"], g["gop"]["label"], e["budget"], t, band(t),
                                 e["qps"][t] - e["ctrl_qps"][t], e["qps"][t] - alone[t]))
    d = pd.DataFrame(rows, columns=["k", "seed", "gid", "clip", "cls", "level", "t", "band", "off", "net"])
    order = [n for _, _, n in BANDS]
    L = [f"# What the residual learns on top of the controller ({codec}, {split})", "",
         "Generated by `scripts/res_offsets.py` (definitions in its docstring). offset = QP used - controller's "
         "proposal at that frame (+ = fewer bits); net = QP used - the controller's standalone run on the same GOP, "
         "level and k. Seeds pooled. Runs found: k = " + ", ".join(map(str, sorted(d.k.unique()))) + ".", ""]
    for k, x in d.groupby("k"):
        dist = x.off.value_counts(normalize=True).reindex(range(-3, 4), fill_value=0) * 100
        L += [f"## k = {k}", "", "**Offset distribution (% of frames)**", "",
              md(pd.DataFrame([dist.round(1).to_dict()]).rename(columns=lambda c: f"{c:+d}")), ""]
        t = x.groupby("band").agg(mean_off=("off", "mean"), mean_abs=("off", lambda s: s.abs().mean()),
                                  net_change=("net", "mean")).reindex(order).reset_index()
        L += ["**By frame position** (mean signed offset, mean |offset|, net QP change vs the standalone controller)",
              "", md(t), ""]
        lv = x.pivot_table(index="band", columns="level", values="off", aggfunc="mean").reindex(order)
        lv.columns = [f"level {c}" for c in lv.columns]
        cl = x.pivot_table(index="band", columns="cls", values="off", aggfunc="mean").reindex(order)
        L += ["**Mean signed offset by position x budget level**", "", md(lv.reset_index()), "",
              "**Mean signed offset by position x GOP class**", "", md(cl.reset_index()), ""]
        sd = x.groupby("seed").off.mean()
        L += [f"Share of offset variance explained by a fixed pattern: position x level {100 * r2(x.off, [x.t, x.level]):.0f}%; "
              f"position x level x clip {100 * r2(x.off, [x['t'], x['level'], x['clip']]):.0f}%. "
              f"Mean offset per seed: " + ", ".join(f"s{s} {v:+.2f}" for s, v in sd.items()) + ".", ""]
    open(f"{OUT}/res_offsets_{codec}.md", "w").write("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main(*sys.argv[1:3])
