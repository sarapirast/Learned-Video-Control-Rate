"""Reward shaping test (tracker item 23): shaped vs unshaped RL runs, paired, on the orig arm (Pavneet's budgets).

Pairs each shaped run <method>_k<k>_fixed_<variant>_s<seed> with the existing <method>_k<k>_fixed_s<seed> (same
method, k, seed, code path; only the training reward / GAE lambda differs). Variants: shape1 (11-09, both methods,
k 0/5); follow-up 23b (11-09, lagr k0 only): shape0.5 (same effective strength as cql_ppo's) and shape1_gae1 (GAE
lambda 1.0, full credit for the end-of-GOP refund) and compares their val and test episodes GOP x budget by GOP x
budget. Reports mean score, saving, % of episodes over budget and mean overshoot for each arm, and the paired
difference (shaped - unshaped) with a 95% bootstrap CI over clips (seeds pooled), plus the per-seed means (PPO
results vary a lot between seeds).

  python -I scripts/shaping_compare.py [x264]
Out: results_v1/shaping_compare_<codec>.md (+ .csv per episode pair)
"""
import os
import pickle
import sys

import numpy as np
import pandas as pd

RC = "/scratch1/aayushso/rcwork_v1"
OUT = "/scratch1/aayushso/ee599/results_v1"
RNG = np.random.default_rng(0)


def episodes(work, run, k, split):
    p = f"{work}/results_rl/{run}/eval.pkl"
    res = pickle.load(open(p, "rb"))["res"][("fixed", k, split)]
    return pd.DataFrame([{"gid": e["gid"], "budget": e["budget"], "score": e["score"], "saving": e["saving"],
                          "over": float(e["over"]), "over_pct": e["over_pct"]} for e in res])


def boot(d, clips, n=2000):
    d, clips = np.asarray(d, float), np.asarray(clips)
    u = np.unique(clips)
    idx = {c: np.flatnonzero(clips == c) for c in u}
    ms = [d[np.concatenate([idx[c] for c in RNG.choice(u, len(u))])].mean() for _ in range(n)]
    return d.mean(), np.percentile(ms, 2.5), np.percentile(ms, 97.5)


def main(codec="x264"):
    work = f"{RC}/{codec}_orig"
    infos = pickle.load(open(f"{work}/results_infos/infos.pkl", "rb"))
    rows = []
    combos = [(m, k, "shape1") for m in ("lagr", "cql_ppo") for k in (0, 5)]
    combos += [("lagr", 0, v) for v in ("shape0.5", "shape1_gae1")
               if all(os.path.exists(f"{work}/results_rl/lagr_k0_fixed_{v}_s{s}/eval.pkl") for s in (0, 1, 2))]
    for method, k, var in combos:
            for seed in (0, 1, 2):
                base, shp = f"{method}_k{k}_fixed_s{seed}", f"{method}_k{k}_fixed_{var}_s{seed}"
                for split in ("val", "test"):
                    a, b = episodes(work, base, k, split), episodes(work, shp, k, split)
                    m = a.merge(b, on=["gid", "budget"], suffixes=("_base", "_shape"), validate="one_to_one")
                    assert len(m) == len(a) == len(b), (base, split)
                    m = m.assign(method=method, k=k, variant=var, seed=seed, split=split,
                                 clip=[infos[g]["gop"]["clip"] for g in m.gid],
                                 cls=[infos[g]["gop"]["label"] for g in m.gid])
                    rows.append(m)
    df = pd.concat(rows, ignore_index=True)
    df.to_csv(f"{OUT}/shaping_compare_{codec}.csv", index=False)

    L = [f"# Reward shaping: shaped vs unshaped runs ({codec}, orig arm)", "",
         "Generated by `scripts/shaping_compare.py`. Shaping: potential-based on predicted overshoot (repo-pavneet "
         "commit 9e031fe, `--shape 1`); everything else identical. Paired by method, k, seed and GOP x budget; 3 seeds "
         "pooled. diff = shaped - unshaped, 95% bootstrap CI over clips. Score: % bits saved vs the GOP's constant-QP "
         "curve minus 2 per 1% over budget.", ""]
    for split in ("test", "val"):
        L += [f"## {split}", "", "| method | k | variant | score base | score shaped | diff score [CI] | saving diff [CI] | "
              "% over base | % over shaped | mean over % base | mean over % shaped |",
              "|---|---|---|---|---|---|---|---|---|---|---|"]
        for (method, k, var), x in df[df.split == split].groupby(["method", "k", "variant"], sort=False):
            ds = boot(x.score_shape - x.score_base, x["clip"])
            dv = boot(x.saving_shape - x.saving_base, x["clip"])
            L.append(f"| {method} | {k} | {var} | {x.score_base.mean():.2f} | {x.score_shape.mean():.2f} | "
                     f"{ds[0]:+.2f} [{ds[1]:+.2f}, {ds[2]:+.2f}] | {dv[0]:+.2f} [{dv[1]:+.2f}, {dv[2]:+.2f}] | "
                     f"{100 * x.over_base.mean():.1f} | {100 * x.over_shape.mean():.1f} | "
                     f"{x.over_pct_base.mean():.2f} | {x.over_pct_shape.mean():.2f} |")
        L += ["", "Per seed (score base -> shaped):", ""]
        for (method, k, var), x in df[df.split == split].groupby(["method", "k", "variant"], sort=False):
            s = x.groupby("seed")[["score_base", "score_shape"]].mean()
            L.append(f"- {method} k={k} {var}: " + "; ".join(f"s{i} {r.score_base:.2f} -> {r.score_shape:.2f}"
                                                      for i, r in s.iterrows()))
        L += ["", "By GOP class (score diff, seeds and k pooled per method):", ""]
        for (method, var), x in df[df.split == split].groupby(["method", "variant"], sort=False):
            L.append(f"- {method} {var}: " + "; ".join(
                f"{c} {(y.score_shape - y.score_base).mean():+.2f} (n={len(y)})" for c, y in x.groupby("cls")))
        L.append("")
    out = f"{OUT}/shaping_compare_{codec}.md"
    open(out, "w").write("\n".join(L) + "\n")
    print("\n".join(L))
    print(f"-> {out}")


if __name__ == "__main__":
    main(*sys.argv[1:2])
