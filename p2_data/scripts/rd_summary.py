"""Checks and summary of the native constant-QP curves and first-pass bits (item 13; scripts/rd_native.py output).

  python scripts/rd_summary.py          -> docs/rd-native-summary.md

1. Sanity: per GOP, bits must fall and PSNR-Y must not rise as QP increases (counts of violations).
2. Typical GOP size and PSNR per encoder at a few QPs (test split medians).
3. x265 vs x264 at equal QP and at equal PSNR (per-GOP bits ratio, medians).
4. P1's frozen settings vs the v1 rerun (Pavneet's harness: preset fast, psy on): per-GOP bits ratio at QP 30/38,
   from the rerun's infos 'curve' (same GOPs, same constant-QP mode).
5. First pass: correlation of first-pass bits (QP 30 and 32) with constant-QP bits, per frame and per GOP.
"""
import pickle

import numpy as np
import pandas as pd

D = "/scratch1/aayushso/ee599/data/v1/320x180"
rd = pd.read_parquet(f"{D}/rd/rd_native.parquet")
fr = pd.read_parquet(f"{D}/rd/rd_frames.parquet")
fp = pd.read_parquet(f"{D}/features/fp_bits.parquet")
rd["bits"] = rd.slice_bits
L = ["# Native constant-QP curves and first-pass bits: checks and summary", "",
     "Generated by `scripts/rd_summary.py` from `data/v1/320x180/rd/rd_native.parquet`, `rd_frames.parquet` and "
     "`features/fp_bits.parquet` (`scripts/rd_native.py`, P1's frozen settings). Bits are slice bits (headers "
     "excluded).", ""]

# 1. sanity
viol = []
for enc, g in rd.sort_values("qp").groupby("encoder"):
    db = g.groupby(["clip_id", "gop"]).bits.apply(lambda s: int((np.diff(s.to_numpy()) >= 0).sum()))
    dp = g.groupby(["clip_id", "gop"]).psnr_y_mean_frames.apply(lambda s: int((np.diff(s.to_numpy()) > 0.05).sum()))
    viol.append({"encoder": enc, "GOPs": len(db), "QP steps checked": int(len(db) * 32),
                 "steps where bits did not fall": int(db.sum()), "GOPs affected (bits)": int((db > 0).sum()),
                 "steps where PSNR-Y rose > 0.05 dB": int(dp.sum()), "GOPs affected (PSNR)": int((dp > 0).sum())})
L += ["## 1. Monotonicity", "", pd.DataFrame(viol).to_markdown(index=False), ""]
hdr = rd.groupby("encoder").header_bits.agg(["min", "median", "max"])
L += ["Header bits per GOP (SPS/PPS/VPS/SEI), excluded from all bit counts above and below:", "",
      hdr.to_markdown(), ""]

# 2. typical sizes
t = rd[rd.split == "test"]
rows = []
for (enc, q), g in t[t.qp.isin([22, 30, 38, 46])].groupby(["encoder", "qp"]):
    rows.append({"encoder": enc, "QP": q, "median kbit/GOP": g.bits.median() / 1e3,
                 "median I-frame share": (g.i_slice_bits / g.bits).median(),
                 "median PSNR-Y (mean of frames)": g.psnr_y_mean_frames.median(),
                 "median PSNR-Y (from mean MSE)": g.psnr_y_from_mse.median()})
L += ["## 2. Typical GOP (test split, medians)", "", pd.DataFrame(rows).round(3).to_markdown(index=False), ""]

# 3. x265 vs x264
w = rd.pivot_table(index=["clip_id", "gop", "qp"], columns="encoder", values=["bits", "psnr_y_mean_frames"])
w.columns = [f"{a}_{b}" for a, b in w.columns]
w = w.reset_index()
eq_qp = (w.bits_x265 / w.bits_x264).groupby(w.qp).median()


def bits_at_psnr(g, enc, p):
    gg = g.sort_values(f"psnr_y_mean_frames_{enc}")
    return np.exp(np.interp(p, gg[f"psnr_y_mean_frames_{enc}"], np.log(gg[f"bits_{enc}"])))


eqp = []
for (c, gop), g in w.groupby(["clip_id", "gop"]):
    lo = max(g.psnr_y_mean_frames_x264.min(), g.psnr_y_mean_frames_x265.min())
    hi = min(g.psnr_y_mean_frames_x264.max(), g.psnr_y_mean_frames_x265.max())
    for p in (32.0, 36.0, 40.0):
        if lo <= p <= hi:
            eqp.append({"psnr": p, "ratio": bits_at_psnr(g, "x265", p) / bits_at_psnr(g, "x264", p)})
eqp = pd.DataFrame(eqp).groupby("psnr").ratio.agg(["median", "count"])
L += ["## 3. x265 vs x264 (all GOPs; ratio of x265 bits to x264 bits, median over GOPs)", "",
      "At equal QP:", "", eq_qp[eq_qp.index.isin([22, 30, 38, 46])].rename("x265/x264 bits").round(3).to_frame()
      .to_markdown(), "", "At equal PSNR-Y (log-bits interpolated along each GOP's curve):", "",
      eqp.round(3).rename(columns={"median": "x265/x264 bits", "count": "GOPs"}).to_markdown(), ""]

# 4. P1 settings vs the rerun's harness
cmp = []
for enc in ("x264", "x265"):
    inf = pickle.load(open(f"/scratch1/aayushso/rcwork_v1/{enc}_orig/results_infos/infos.pkl", "rb"))
    mine = rd[rd.encoder == enc].set_index(["clip_id", "gop", "qp"])
    for gid, x in inf.items():
        clip, start = gid.split("@")
        gop = int(start) // 30
        cq = dict(zip(np.asarray(x["curve"]["qps"]).astype(int), np.asarray(x["curve"]["bits"], float))) \
            if "qps" in x["curve"] else None
        if cq is None:
            continue
        for q in (30, 38):
            if q in cq and (clip, gop, q) in mine.index:
                cmp.append({"encoder": enc, "qp": q, "ratio": mine.loc[(clip, gop, q), "bits"] / cq[q]})
if cmp:
    c = pd.DataFrame(cmp).groupby(["encoder", "qp"]).ratio.agg(["median", lambda s: np.percentile(s, 10),
                                                                 lambda s: np.percentile(s, 90), "count"])
    c.columns = ["median", "p10", "p90", "GOPs"]
    L += ["## 4. P1's frozen settings vs the v1 rerun's settings (bits ratio P1 / rerun, same GOP and QP)", "",
          "The rerun's curve counts SPS/PPS with frame 0's bits; that adds well under 0.5% at these sizes.", "",
          c.round(4).to_markdown(), ""]
else:
    L += ["## 4. P1 settings vs rerun", "", "The rerun's infos curve has no QP column; comparison skipped.", ""]

# 5. first pass vs constant QP
cq = fr[(fr.kind == "cqp") & (fr.qp == 30)][["encoder", "clip_id", "gop", "frame", "slice_bits"]]
out = []
for fq in (30, 32):
    m = cq.merge(fp[fp.fp_qp == fq], on=["encoder", "clip_id", "gop", "frame"])
    for enc, g in m.groupby("encoder"):
        p_frames = g[g.frame > 0]
        r_frame = np.corrcoef(np.log(p_frames.fp_slice_bits.clip(lower=8)), np.log(p_frames.slice_bits.clip(lower=8)))[0, 1]
        gg = g.groupby(["clip_id", "gop"])[["fp_slice_bits", "slice_bits"]].sum()
        r_gop = np.corrcoef(np.log(gg.fp_slice_bits), np.log(gg.slice_bits))[0, 1]
        out.append({"encoder": enc, "first-pass QP": fq, "corr per P frame (log bits)": r_frame,
                    "corr per GOP (log bits)": r_gop,
                    "median first-pass / CQP-30 bits": (gg.fp_slice_bits / gg.slice_bits).median()})
L += ["## 5. First-pass bits vs constant-QP 30 bits", "", pd.DataFrame(out).round(3).to_markdown(index=False), ""]
open("/scratch1/aayushso/ee599/docs/rd-native-summary.md", "w").write("\n".join(L) + "\n")
print("\n".join(L))
