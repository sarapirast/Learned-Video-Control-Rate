"""Milestone headline tables for the v1 rerun of Pavneet's pipeline, both encoders (no encodes).

Reads results_v1/<codec>_arm_compare.csv (scripts/v1_arm_compare.py) and Pavneet's search/baseline stage caches.
Writes results_v1/v1_headline.md. Test split throughout; scores are % saving at equal PSNR vs constant QP minus
2 x % over budget, averaged over (GOP, budget) items after averaging seeds.
"""
import os
import sys

import numpy as np
import pandas as pd

REPO = "/scratch1/aayushso/ee599/repo-pavneet"
sys.path.insert(0, REPO)
from rclib import config as C, metrics, runner  # noqa: E402

R = "/scratch1/aayushso/ee599/results_v1"
L = ["# v1 headline results (test split, both encoders)", "",
     "Generated by `scripts/v1_headline.py` from `results_v1/<codec>_arm_compare.csv` and the pipeline's stage "
     "caches. orig = Pavneet's budget (the GOP's own constant-QP spend at QP 30/38); dec = that budget x s, "
     "s ~ U(0.8, 1.25). Score = % bits saved at equal PSNR vs constant QP - 2 x % over budget.", ""]

# 1. search and baselines (orig arm)
rows = []
for codec in ("x264", "x265"):
    C.WORK = f"/scratch1/aayushso/rcwork_v1/{codec}_orig"
    infos = runner.Stages("infos").load("infos")
    srch = runner.Stages("search").load("search_test")
    best = [x["best_score"] for r in srch.values() for x in r.values()]
    stat = [infos[g]["static"][b]["score"] for g, r in srch.items() for b in r]
    own = runner.Stages("baselines").load("own_rc")
    test = [g for g, x in infos.items() if x["gop"]["split"] == "test"]
    def own_s(mode, aq):
        rr = [own[g][(b, mode, aq)] for g in test if g in own for b in C.BUDGET_QPS]
        rr = [r for r in rr if not r.get("failed")]
        return metrics.summarize(rr)
    abr = own_s("abr_vbv", False)
    rows.append({"encoder": codec, "hindsight search": np.mean(best), "STATIC (fixed pattern)": np.mean(stat),
                 "x26x ABR+VBV score": abr["score"], "ABR+VBV over %": abr["over_pct"]})
L += ["## Reference points (orig arm)", "", pd.DataFrame(rows).round(2).to_markdown(index=False), ""]

# 2. learned policies by k
t = pd.concat([pd.read_csv(f"{R}/{c}_arm_compare.csv").assign(encoder=c) for c in ("x264", "x265")])
piv = t.pivot_table(index=["encoder", "method", "arm"], columns="k", values="score").round(2)
piv.columns = [f"k={k}" for k in piv.columns]
L += ["## Learned policies: score by lookahead k", "", piv.reset_index().to_markdown(index=False), ""]

# 3. best k=0 vs best k>0, and the orig -> dec drop at k=0
out = []
for (enc, m), g in t.groupby(["encoder", "method"]):
    for arm, h in g.groupby("arm"):
        k0 = h[h.k == 0].iloc[0]
        kb = h[h.k > 0].sort_values("score").iloc[-1]
        out.append({"encoder": enc, "method": m, "arm": arm, "k=0 score": k0.score, "k=0 over %": k0["over %"],
                    "best k>0": int(kb.k), "best k>0 score": kb.score, "gain vs k=0 (paired, 95% CI)": kb["vs k=0"],
                    "share of search gain at k=0": k0["share of search gain"]})
L += ["## Does lookahead help? (k=0 vs the best k>0, same method and arm)", "",
      pd.DataFrame(out).round(2).to_markdown(index=False), ""]
drop = []
for (enc, m), g in t[t.k == 0].groupby(["encoder", "method"]):
    if set(g.arm) == {"orig", "dec"}:
        o, d = g[g.arm == "orig"].score.iloc[0], g[g.arm == "dec"].score.iloc[0]
        drop.append({"encoder": enc, "method": m, "k=0 orig": o, "k=0 dec": d, "drop": o - d})
L += ["## Budget leak: k=0 score, original vs decoupled budget", "",
      pd.DataFrame(drop).round(2).to_markdown(index=False), "",
      "Caveat: the decoupled arm only partly removes the leak (the budget still tracks the GOP's cost to within "
      "about +-12%). The clean test needs clip-level budgets and a causal base-QP estimator.", ""]
open(f"{R}/v1_headline.md", "w").write("\n".join(L) + "\n")
print("\n".join(L))
